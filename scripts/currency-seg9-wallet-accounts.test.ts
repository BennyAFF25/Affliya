import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const name = '20261015170000_currency_seg9_wallet_accounts';
const clean = (s: string) => s.replace(/--[^\n]*/g, '').replace(/\s+/g, ' ').trim();
const sql = clean(readFileSync(`supabase/migrations/${name}.sql`, 'utf8'));
const undo = clean(readFileSync(`supabase/undo/${name}.undo.sql`, 'utf8'));
assert.match(sql, /^BEGIN; .* COMMIT;$/);
assert.match(sql, /CREATE TABLE public\.wallet_accounts \(/);
assert.match(sql, /id uuid PRIMARY KEY DEFAULT gen_random_uuid\(\)/);
assert.match(sql, /owner_email text NOT NULL/);
assert.match(sql, /owner_user_id uuid NULL/);
assert.match(sql, /owner_role text NOT NULL DEFAULT 'affiliate' CHECK \(owner_role IN \('affiliate', 'business', 'platform'\)\)/);
assert.match(sql, /currency text NOT NULL REFERENCES public\.currency_registry\(code\)/);
assert.match(sql, /status text NOT NULL DEFAULT 'active' CHECK \(status IN \('active', 'frozen', 'closed'\)\)/);
assert.match(sql, /created_at timestamptz NOT NULL DEFAULT now\(\)/);
assert.match(sql, /UNIQUE \(owner_email, currency\)/);
assert.match(sql, /CREATE INDEX \w+ ON public\.wallet_accounts \(owner_user_id\)/);
assert.match(sql, /ALTER TABLE public\.wallet_accounts ENABLE ROW LEVEL SECURITY;/);
assert.doesNotMatch(sql, /CREATE POLICY|DISABLE ROW LEVEL SECURITY/i);
assert.match(sql, /REVOKE ALL ON public\.wallet_accounts FROM PUBLIC, anon, authenticated;/);
assert.match(sql, /GRANT ALL ON public\.wallet_accounts TO service_role;/);
assert.equal((sql.match(/\bGRANT\b/gi) ?? []).length, 1);
assert.match(sql, /INSERT INTO public\.wallet_accounts \(owner_email, owner_user_id, owner_role, currency\) SELECT w\.email, NULL::uuid, CASE WHEN w\.role IN \('affiliate', 'business', 'platform'\) THEN w\.role ELSE 'affiliate' END, 'AUD' FROM public\.wallets w ON CONFLICT \(owner_email, currency\) DO NOTHING;/);
assert.match(sql, /SELECT count\(\*\) INTO wallet_count FROM public\.wallets;/);
assert.match(sql, /SELECT count\(\*\) INTO account_count FROM public\.wallet_accounts WHERE currency = 'AUD';/);
assert.match(sql, /IF account_count <> wallet_count THEN RAISE EXCEPTION/);
assert.match(sql, /COMMENT ON TABLE public\.wallet_accounts IS 'Identity-only.*no balances.*Not yet authoritative/);
assert.equal((sql.match(/ALTER TABLE/gi) ?? []).length, 1);
assert.doesNotMatch(sql.replace('ALTER TABLE public.wallet_accounts ENABLE ROW LEVEL SECURITY;', ''), /\bALTER\b|\bUPDATE\b|\bDELETE\b|CREATE (?:OR REPLACE )?(?:FUNCTION|VIEW|TRIGGER)|\bDROP\b/i);
const columns = sql.match(/CREATE TABLE public\.wallet_accounts \((.*?)\);/)?.[1];
assert.ok(columns);
assert.doesNotMatch(columns, /\bbalance\b|\bamount\b|currency text[^,]*DEFAULT/i);
assert.equal(undo, 'BEGIN; DROP TABLE IF EXISTS public.wallet_accounts; COMMIT;');
console.log('Currency Segment 9 wallet accounts static tests passed');
