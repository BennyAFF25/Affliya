import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { WalletBillingNotice } from '../app/affiliate/wallet/WalletBillingNotice';
(globalThis as typeof globalThis & { React: typeof React }).React = React;
let retries = 0;
const props = { loading: true, error: false, ready: false, onRetry: () => { retries++; } };
const render = (overrides = {}) => renderToStaticMarkup(React.createElement(WalletBillingNotice, { ...props, ...overrides }));
assert.match(render(), /Checking billing…/);
assert.doesNotMatch(render(), /Billing connection required|Open settings|Try again/);
assert.match(render({ loading: false }), /Billing connection required/);
assert.match(render({ loading: false }), /Open settings/);
assert.equal(render({ loading: false, ready: true }), '');
const error = render({ loading: false, error: true });
assert.match(error, /Could not check billing.*Try again/);
assert.doesNotMatch(error, /Billing connection required|Open settings/);
assert.doesNotMatch(render({ error: true }), /Try again/);
const element = WalletBillingNotice({ ...props, loading: false, error: true })!;
const button = (element.props as { children: React.ReactElement[] }).children.find(child => React.isValidElement(child));
(button!.props as { onClick: () => void }).onClick();
assert.equal(retries, 1);
console.log('Wallet billing loading, disconnected, connected, error and retry passed');
